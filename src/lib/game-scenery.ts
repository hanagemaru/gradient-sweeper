import { CRYSTAL_BASE, type BackgroundPlacement } from "./background-world";

/**
 * ゲーム画面（`/game`）の背景に置くモチーフ。
 *
 * ホームの `BACKGROUND_WORLD` と違い、これは**手で置いた固定リスト**で、
 * `scripts/generate-background-world.mjs` の生成対象ではない。理由は2つ。
 *
 * 1. 生成器の配置制約はホームの遮蔽物（`HOME_OCCLUDERS` = 中央のパネル1枚と
 *    言語トグル）を前提にしている。ゲーム画面は上部HUD・中央盤面・下部ボタンと
 *    専有領域がまるで違うので、ホームの座標をそのまま敷くとモチーフが盤面の裏へ
 *    ほぼ隠れ、縁から細い帯だけが覗く。生成器が禁じている見え方そのものになる。
 * 2. 空いている場所が1か所しかない。総当たりで探す意味がない。
 *
 * **セルのオートタイルは使わない。** ホームでは氷原の地形として読めるが、
 * ゲーム画面では盤面そのものが同じ雪・氷のセルでできているため、背景に同じ絵柄を
 * 撒くと「開けられるマス」と紛らわしくなる。クリスタルだけに絞っている。
 *
 * === 3個から1個に減った理由（増やす前に読むこと） ===
 *
 * キャンバス高さが 670 だった頃は、HUD と盤面の間（y128〜185）と盤面より下
 * （y527〜670）の2か所が空いていて、3個置けた。
 *
 * iPhone SE で左右の黒帯を消すためにキャンバスを 550 へ詰めた（理由は
 * pixel-ui.module.css の冒頭コメント）結果、倍率1での実測はこうなった。
 *
 *   HUD          y[ 10, 119]（落ち影は y131 まで）
 *   盤面フレーム   y[139, 481] x[24, 366]（落ち影は y493 / x372 まで）
 *   操作ボタン     y[500, 540]（落ち影は y545 まで）
 *
 * HUD と盤面の間は 8px しか残らず、置ける場所は**盤面より下の y[493,550] の
 * 57px だけ**になった。しかもその帯は操作ボタンに左右へ分断されている。
 *
 * 2個置けない理由は「見えているモチーフ同士を横一線に並べない」（ホームと共通の
 * 規則。`ROW_MIN_OFFSET` = 中心Yを 40px 以上ずらす）を満たせないため。
 * 帯が 57px しかないので、左右に1個ずつ置くと中心Yの差は最大でも十数pxにしかならず、
 * ボタンを挟んで左右に並んだ一直線に見えてしまう。よって1個だけ置く。
 *
 * ホストと共通で守っている規則:
 * - クリスタルは上下左右のどこでも欠けさせない（不透明部分をキャンバス内に収める）
 * - UI に隠れて細い帯だけが覗く配置にしない
 * - 見えているモチーフ同士を横一線に並べない
 *
 * 座標はキャンバス（390x550）基準。レイアウトを変えたら
 * `src/app/game/game.module.css` の配分と合わせて取り直すこと。
 */
export const GAME_SCENERY: BackgroundPlacement[] = [
  /*
   * 盤面より下、操作ボタンの左。
   * cluster-wide は 120x80 で不透明部分が (3,35) から 114x45。
   *   不透明 y = 466+35 .. 466+80 = [501, 546]
   *     → 盤面の落ち影の下端 493 より下、キャンバス下端 550 の内側（余白4px）
   *   不透明 x = 6+3 .. 6+117 = [9, 123]
   *     → 操作ボタン左端 133 まで 10px 空く
   */
  { base: CRYSTAL_BASE, name: "cluster-wide", x: 6, y: 466, w: 120, h: 80 },
];
